
package ejerciciocontador;

public class Contador {
    
    public void contador(int numero){
        
        System.out.println("Iniciando contador....");
        
        System.out.println("------------------------------------");
        
        System.out.println("Mostrando números: ");
        for(int i=1; i<=numero; i++){
            System.out.println("Número: " + i);
        }
        

        
    }
    
    
}
